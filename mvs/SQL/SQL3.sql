-- FINAL QUERY - JOIN WITH ALL TABLES TO GET ALL REQUIRED COLUMNS

SELECT EPA.ACTNO, D.MGRNO, EPA.EMSTDATE, EPA.PROJNO, E.LASTNAME
  FROM IBMUSER.EMPPROJACT EPA
 INNER JOIN IBMUSER.PROJ P ON EPA.PROJNO = P.PROJNO
 INNER JOIN IBMUSER.DEPT D ON P.DEPTNO = D.DEPTNO
 INNER JOIN IBMUSER.EMP E ON EPA.EMPNO = E.EMPNO
 WHERE EPA.EMSTDATE >= '1982-10-15'
 ORDER BY EPA.ACTNO, EPA.EMSTDATE;

