SELECT * FROM IBMUSER.EMP;


-- 4.1 THE CTE

WITH TEMP AS (
  SELECT YEAR(HIREDATE) AS HIREYEAR,
         SALARY + BONUS + COMM AS TOTAL_EARNINGS
    FROM IBMUSER.EMP
   WHERE HIREDATE BETWEEN '1970-01-01' AND '1980-12-31'
)

SELECT HIREYEAR,
       DECIMAL(AVG(TOTAL_EARNINGS), 10, 2) AS AVG_TOTAL_EARNINGS
  FROM TEMP
 GROUP BY HIREYEAR;

