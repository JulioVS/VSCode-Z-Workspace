-- Part B: The Recursive Query

WITH CAR_PARTS (LEVEL, ASSEMBLY, COMPONENT, QUANTITY) AS
(
     SELECT 0 AS LEVEL, ASSEMBLY, COMPONENT, QUANTITY
       FROM CARS AS ROOT
      WHERE LEVEL = 2
        AND ASSEMBLY = 'PASSENGER COMPARTMENT'
      UNION ALL
     SELECT PARENT.LEVEL + 1, CHILD.ASSEMBLY, CHILD.COMPONENT, CHILD.QUANTITY
       FROM CAR_PARTS AS PARENT
       JOIN CARS AS CHILD ON PARENT.COMPONENT = CHILD.ASSEMBLY
        AND PARENT.LEVEL < 1
)

SELECT *
  FROM CAR_PARTS
 ORDER BY LEVEL, ASSEMBLY, COMPONENT;

-- BONUS EXAMPLE: RECURSIVE NUMBER SEQUENCE

WITH NumberSequence (num) AS
(
     -- Anchor: Start with 1 (runs once)
     SELECT 1 AS num
       FROM SYSIBM.SYSDUMMY1

      UNION ALL

     -- Recursive member: Add 1 to the previous value (loops)
     SELECT num + 1
       FROM NumberSequence
      WHERE num < 5 -- Termination condition
)

SELECT num
  FROM NumberSequence;

