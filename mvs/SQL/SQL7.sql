-- 4.1 CREATE A TABLE

CREATE TABLE TESTEMP
(
    EMPNO     CHAR(6)        NOT NULL,
    LASTNAME  VARCHAR(15)    NOT NULL,
    WORKDEPT  CHAR(3)                ,
    HIREDATE  DATE                   ,
    SALARY    DECIMAL(9,2)           ,
    BONUS     DECIMAL(9,2)           ,
    PRIMARY KEY(EMPNO)
)
IN DATABASE Z45864;

-- 4.2 THE NEW EMPLOYEES (INSERT)

